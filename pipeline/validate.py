"""Check our numbers against the State of New Jersey's (docs/methodology.md Section 8).

The state's average ratio comes from a "weighted, classified and multi-year-averaged
sales study" (Tax Court, City of New Brunswick v. Director, 2026; source note
data/raw/notes/director-average-ratio-method.md). For each town:

1. One-year true value = each class's assessed total / that class's sales ratio
   (weighted: total assessed / total price), added up.
2. Aggregate true value = average of (1) and the prior year's aggregate true value.
3. Average ratio = aggregate assessed / (2).

So we compare, for all 70 Bergen towns (rule V4):
- the state's ONE-YEAR ratio, backed out of the 2025 and 2026 Tables of Equalized
  Valuations (one-year true value = 2 x TV 2026 - TV 2025), against our own
  one-year ratio built from the same usable Sales2026 sales; and
- the published 2027 average ratio against our two-year version of it.
Also: our plain average of the same sales (first try), our class-2 median (V3),
the state's coefficient of deviation (V2), and the state's average sale price.

Writes data/processed/validation.csv and the generated block inside
docs/validation.md (the rest of that file is written by hand and kept).
Ratios in this file are percents (80.0 = 80%), like the state's tables.

Run after the stats stage:
.venv\\Scripts\\python.exe -m pipeline.validate
"""

