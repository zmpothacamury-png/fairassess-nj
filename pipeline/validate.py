# ---------------------------------------------------------------- sales sets

def state_style_sales(sr1a):
    """Usable Bergen sales in the state's study classes (1, 2, 4), with sale price and ratio (percent).

    Sale price follows methodology Section 3.1: VERIFIED-SALES-PRICE, or
    REPORTED-SALES-PRICE when the verified price is zero or blank. Assessed
    value is TOTAL ASSESSMENT (main lot plus extra lots), because that is what
    the state pairs with the price: the state's own SALES-RATIO field equals
    TOTAL ASSESSMENT / price on every multi-lot sale (rule V2).
    ratio_main_pct (main lot only) is kept to show what that choice changes.
    """
    df = sr1a[(sr1a["county_code"] == config.COUNTY_CODE) & (sr1a["un_type"] == config.USABLE_CODE)].copy()
    # Leading number of the class: "4A" -> "4", "2" -> "2", "15C" -> "15" (exempt, not class 1).
    df["class_group"] = df["property_class"].str.strip().str.extract(r"^(\d+)", expand=False)
    df = df[df["class_group"].isin(config.STATE_STUDY_CLASSES)]
    verified_ok = df["price_verified"].fillna(0) > 0
    df["sale_price"] = df["price_verified"].where(verified_ok, df["price_reported"]).astype(float)
    df["assessed"] = df["total_assessment"].astype(float)
    df["ratio_pct"] = 100 * df["assessed"] / df["sale_price"]
    df["ratio_main_pct"] = 100 * df["av_total"].astype(float) / df["sale_price"]
    return df.reset_index(drop=True)


def mean_deviation(ratios):
    """State-style coefficient (V2) = 100 x average of |R_i - mean ratio| / mean ratio."""
    r = np.asarray(ratios, dtype=float)
    m = r.mean()
    return float(100 * np.mean(np.abs(r - m)) / m)


def weighted_ratio(group):
    """Weighted ratio of a group of sales, as a decimal: total assessed / total price (None if no sales)."""
    return stats.weighted_mean_ratio(group["assessed"], group["sale_price"]) if len(group) else None


def one_year_true_value(agg_assessed, residential_assessed, class2_ratio, other_ratio):
    """Our one-year true value, the state's way: each class's assessed total / its sales ratio, added up.

    Two classes: residential (class 2) and everything else (classes 1 and 4 have
    too few sales to split). If a town has no sales in one group, its assessed
    total is valued at the other group's ratio (our choice, rule V4).
    """
    other_assessed = max(agg_assessed - residential_assessed, 0.0)
    r2 = class2_ratio if class2_ratio is not None else other_ratio
    ro = other_ratio if other_ratio is not None else class2_ratio
    if r2 is None:
        return None
    return residential_assessed / r2 + other_assessed / ro


def averaged_true_value(one_year, prior_aggregate):
    """Aggregate true value = average of this year's one-year true value and last year's aggregate."""
    return (one_year + prior_aggregate) / 2


def state_one_year_true_value(true_value_now, true_value_prior):
    """Back out the state's one-year true value: if TV_now = (one_year + TV_prior) / 2, one_year = 2 x TV_now - TV_prior."""
    return 2 * true_value_now - true_value_prior


# ---------------------------------------------------------------- per-town numbers

def _round(x, digits=2):
    """Round a number, keeping blanks blank."""
    return None if x is None or pd.isna(x) else round(float(x), digits)


def ours_by_town(state_sales, clean):
    """Our sales-based numbers for each town that has any sales (keyed by district_code)."""
    rows = {}
    for code, g in state_sales.groupby("district_code", sort=True):
        c2 = g[g["class_group"] == config.RESIDENTIAL_CLASS]
        other = g[g["class_group"] != config.RESIDENTIAL_CLASS]
        rows[code] = {
            "our_n_classes_1_2_4": len(g),
            "our_simple_mean_ratio": stats.mean_ratio(g["ratio_pct"]),
            "class2_weighted_ratio": weighted_ratio(c2),
            "other_weighted_ratio": weighted_ratio(other),
            "n_class1": int((g["class_group"] == "1").sum()),
            "n_class2_usable": len(c2),
            "n_class4": int((g["class_group"] == "4").sum()),
            "n_multi_lot": int((g["total_assessment"] > g["av_total"]).sum()),
            "min_ratio": g["ratio_pct"].min(),
            "max_ratio": g["ratio_pct"].max(),
            "first_recorded": g["recorded_date"].min().date().isoformat(),
            "last_recorded": g["recorded_date"].max().date().isoformat(),
            "share_old_assessment": float((g["assess_year"] < config.REVAL_MIN_ASSESS_YEAR).mean()),
            "our_cod_state_style": mean_deviation(c2["ratio_pct"]) if len(c2) else None,
            "our_cod_main_lot": mean_deviation(c2["ratio_main_pct"]) if len(c2) else None,
            "our_mean_price_class2_usable": c2["sale_price"].mean() if len(c2) else None,
        }
    for code, g in clean.groupby("district_code", sort=True):
        row = rows.setdefault(code, {})
        row["n_clean"] = len(g)
        row["our_class2_median"] = 100 * stats.median_ratio(g["ratio"])
        row["our_median_price_clean"] = float(g["sale_price"].median())
    return rows


def category_27_by_town(sr1a):
    """Non-usable Bergen sales (any class) with state code 27: recorded July to December before a revaluation."""
    b = sr1a[(sr1a["county_code"] == config.COUNTY_CODE) & (sr1a["un_type"] != config.USABLE_CODE)]
    return b[b["sr_nu_code"].str.strip() == "27"].groupby("district_code").size()


def state_by_town(inputs):
    """The state's numbers for each Bergen town (keyed by district_code)."""
    ch = inputs["ch123"].set_index("district_code")
    cod = inputs["state_cod"]
    cod = cod[cod["year"] == config.STATE_COD_YEAR].set_index("district_code")
    res = inputs["avg_res"].set_index("district_code")
    dr = inputs["dir_ratios"].pivot(index="district_code", columns="year", values="director_ratio")
    tev = inputs["tev"].pivot(index="district_code", columns="year")
    out = pd.DataFrame({
        "state_average_ratio": ch["average_ratio"],
        "state_director_ratio_2026": dr[STUDY_YEAR],
        "state_ratio_2025": tev[("average_ratio", PRIOR_YEAR)],
        "agg_assessed_2025": tev[("agg_assessed", PRIOR_YEAR)],
        "agg_assessed_2026": tev[("agg_assessed", STUDY_YEAR)],
        "agg_true_value_2025": tev[("agg_true_value", PRIOR_YEAR)],
        "agg_true_value_2026": tev[("agg_true_value", STUDY_YEAR)],
        "tev_ratio_2026": tev[("average_ratio", STUDY_YEAR)],
        "residential_assessed": res["line_items"] * res["avg_assessment"],
        "state_n_classes_1_2_4": cod["n_total"],
        "state_cod_class2": cod["stratified_class2"],
        "state_n_class2": res["n_sales"],
        "state_avg_sale_price": res["avg_sale_price"],
    })
    out["state_one_year_true_value"] = state_one_year_true_value(out["agg_true_value_2026"],
                                                                 out["agg_true_value_2025"])
    out["state_one_year_ratio"] = 100 * out["agg_assessed_2026"] / out["state_one_year_true_value"]
    return out


def validation_table(inputs):
    """One row per town (all 70): both sides of every comparison, the gaps, and the flags."""
    towns = inputs["towns"].sort_values("district_code").set_index("district_code")
    state = state_by_town(inputs).reindex(towns.index)
    ours = pd.DataFrame.from_dict(ours_by_town(state_style_sales(inputs["sr1a"]), inputs["clean"]),
                                  orient="index").reindex(towns.index)
    for col in ["class2_weighted_ratio", "other_weighted_ratio"]:
        ours[col] = ours[col].astype(object).where(ours[col].notna(), None)
    iaao = inputs["town_stats"].set_index("district_code")["cod"].reindex(towns.index)

    tv_ours = pd.Series([one_year_true_value(a, r, c2, o) if not pd.isna(a) and not pd.isna(r) else None
                         for a, r, c2, o in zip(state["agg_assessed_2026"], state["residential_assessed"],
                                                ours["class2_weighted_ratio"], ours["other_weighted_ratio"])],
                        index=towns.index, dtype=float)

    t = pd.DataFrame(index=towns.index)
    t["town"] = towns["display_name"]
    t["revaluation_tax_year"] = towns["revaluation_tax_year"].astype("Int64")
    # V4 one-year comparison (the headline).
    t["state_one_year_ratio"] = state["state_one_year_ratio"]
    t["our_ratio_state_style"] = 100 * state["agg_assessed_2026"] / tv_ours
    t["diff_one_year_pp"] = t["our_ratio_state_style"] - t["state_one_year_ratio"]
    t["flag_over_5pp"] = t["diff_one_year_pp"].abs() > config.VALIDATION_FLAG_PP
    # Published ratio and our two-year version of it.
    t["state_average_ratio"] = state["state_average_ratio"]
    t["our_average_ratio_two_year"] = (100 * state["agg_assessed_2026"]
                                       / averaged_true_value(tv_ours, state["agg_true_value_2025"]))
    t["diff_two_year_pp"] = t["our_average_ratio_two_year"] - t["state_average_ratio"]
    t["averaging_effect_pp"] = t["state_average_ratio"] - t["state_one_year_ratio"]
    # First try: a plain average of the same sales.
    t["our_simple_mean_ratio"] = ours["our_simple_mean_ratio"]
    t["diff_simple_mean_pp"] = t["our_simple_mean_ratio"] - t["state_average_ratio"]
    t["our_n_classes_1_2_4"] = ours["our_n_classes_1_2_4"].fillna(0).astype(int)
    t["state_n_classes_1_2_4"] = state["state_n_classes_1_2_4"].fillna(0).astype(int)
    t["counts_match"] = t["our_n_classes_1_2_4"] == t["state_n_classes_1_2_4"]
    # V3: our published class-2 median.
    t["our_class2_median"] = ours["our_class2_median"]
    t["n_clean"] = ours["n_clean"].fillna(0).astype(int)
    t["diff_class2_median_pp"] = t["our_class2_median"] - t["state_average_ratio"]
    t["v3_flag_over_10pp"] = t["diff_class2_median_pp"].abs() > config.V3_FLAG_PP
    # V2: coefficient of deviation.
    t["state_cod_class2"] = state["state_cod_class2"]
    t["our_cod_state_style"] = ours["our_cod_state_style"]
    t["diff_cod"] = t["our_cod_state_style"] - t["state_cod_class2"]
    has_cod = t["state_cod_class2"].notna() & t["our_cod_state_style"].notna()
    t["v2_pass"] = (t["diff_cod"].abs() <= config.V2_PASS_PP).where(has_cod)
    t["our_cod_main_lot"] = ours["our_cod_main_lot"]
    t["our_iaao_cod"] = iaao
    # Sale prices (rough sense check).
    t["state_avg_sale_price"] = state["state_avg_sale_price"]
    t["state_n_class2"] = state["state_n_class2"].fillna(0).astype(int)
    t["our_mean_price_class2_usable"] = ours["our_mean_price_class2_usable"]
    t["our_median_price_clean"] = ours["our_median_price_clean"]
    t["price_diff_pct"] = 100 * (t["our_median_price_clean"] / t["state_avg_sale_price"] - 1)
    # Evidence for the investigation.
    for col in ["n_class1", "n_class2_usable", "n_class4", "n_multi_lot"]:
        t[col] = ours[col].fillna(0).astype(int)
    t["class2_weighted_ratio"] = 100 * ours["class2_weighted_ratio"].astype(float)
    t["other_weighted_ratio"] = 100 * ours["other_weighted_ratio"].astype(float)
    t["residential_share_assessed"] = state["residential_assessed"] / state["agg_assessed_2026"]
    for col in ["agg_assessed_2025", "agg_assessed_2026", "agg_true_value_2025", "state_one_year_true_value"]:
        t[col] = state[col]
    t["our_one_year_true_value"] = tv_ours
    for col in ["min_ratio", "max_ratio", "share_old_assessment", "first_recorded", "last_recorded"]:
        t[col] = ours[col]
    t["n_nonusable_cat27"] = category_27_by_town(inputs["sr1a"]).reindex(towns.index).fillna(0).astype(int)
    t["state_ratio_2025"] = state["state_ratio_2025"]
    t["state_director_ratio_2026"] = state["state_director_ratio_2026"]
    t["tev_ratio_2026"] = state["tev_ratio_2026"]

    t["flag_rank"] = t["diff_one_year_pp"].abs().where(t["flag_over_5pp"]).rank(
        ascending=False, method="first").astype("Int64")
    t["investigated"] = t["flag_rank"].le(config.VALIDATION_MAX_INVESTIGATE).fillna(False).astype(bool)

    money = ["state_avg_sale_price", "our_mean_price_class2_usable", "our_median_price_clean",
             "agg_assessed_2025", "agg_assessed_2026", "agg_true_value_2025", "state_one_year_true_value",
             "our_one_year_true_value"]
    for col in t.columns:
        if col in money:
            t[col] = t[col].map(lambda x: _round(x, 0))
        elif col in ("share_old_assessment", "residential_share_assessed"):
            t[col] = t[col].map(lambda x: _round(x, 4))
        elif t[col].dtype == float:
            t[col] = t[col].map(_round)
    return t.reset_index()


# ---------------------------------------------------------------- summary

def summarize(t):
    """Headline counts for the report (all from the validation table)."""
    d1 = t["diff_one_year_pp"].dropna()
    d2 = t["diff_two_year_pp"].dropna()
    ds = t["diff_simple_mean_pp"].dropna()
    has_c2 = t["our_class2_median"].notna()
    v2 = t["v2_pass"].dropna()
    price = t.dropna(subset=["price_diff_pct"])
    return {
        "n_towns": len(t),
        "n_one_year": len(d1),
        "one_year_within_flag": int((d1.abs() <= config.VALIDATION_FLAG_PP).sum()),
        "one_year_within_2": int((d1.abs() <= 2).sum()),
        "one_year_within_1": int((d1.abs() <= 1).sum()),
        "one_year_median_diff": float(d1.median()),
        "n_flagged": int(t["flag_over_5pp"].sum()),
        "max_abs_one_year": float(d1.abs().max()),
        "max_abs_one_year_town": t.loc[d1.abs().idxmax(), "town"],
        "two_year_within_flag": int((d2.abs() <= config.VALIDATION_FLAG_PP).sum()),
        "two_year_within_1": int((d2.abs() <= 1).sum()),
        "simple_within_flag": int((ds.abs() <= config.VALIDATION_FLAG_PP).sum()),
        "simple_state_higher": int((ds < 0).sum()),
        "simple_median_diff": float(ds.median()),
        "averaging_median": float(t["averaging_effect_pp"].median()),
        "averaging_positive": int((t["averaging_effect_pp"] > 0).sum()),
        "counts_match": int(t["counts_match"].sum()),
        "total_ours": int(t["our_n_classes_1_2_4"].sum()),
        "total_state": int(t["state_n_classes_1_2_4"].sum()),
        "director_equals_ch123": int((t["state_director_ratio_2026"] == t["state_average_ratio"]).sum()),
        "tev_equals_ch123": int((t["tev_ratio_2026"] == t["state_average_ratio"]).sum()),
        "n_with_class2_median": int(has_c2.sum()),
        "class2_within_flag": int((has_c2 & (t["diff_class2_median_pp"].abs() <= config.VALIDATION_FLAG_PP)).sum()),
        "v3_flagged": int(t["v3_flag_over_10pp"].sum()),
        "class2_median_diff": float(t["diff_class2_median_pp"].median()),
        "v2_n": len(v2),
        "v2_pass": int(v2.sum()),
        "v2_pass_main_lot": int(((t["our_cod_main_lot"] - t["state_cod_class2"]).abs()
                                 <= config.V2_PASS_PP)[t["v2_pass"].notna()].sum()),
        "n_multi_lot": int(t["n_multi_lot"].sum()),
        "state_above_every_sale": int((t["state_average_ratio"] > t["max_ratio"]).sum()),
        "state_above_every_sale_towns": ", ".join(t.loc[t["state_average_ratio"] > t["max_ratio"], "town"]),
        "price_n": len(price),
        "price_median_diff_pct": float(price["price_diff_pct"].median()),
        "price_mean_matches": int((t["our_mean_price_class2_usable"].round(0)
                                   == t["state_avg_sale_price"].round(0)).sum()),
    }


def headline(s):
    """The one-sentence result."""
    return (f"For {s['one_year_within_flag']} of {s['n_one_year']} towns, our ratio was within "
            f"{config.VALIDATION_FLAG_PP:g} points of the state's, and for {s['one_year_within_1']} it was within "
            f"1 point, once we follow the state's method (weighted by property class, before the state averages "
            f"in last year).")


def group_table(t):
    """One-year gap by revaluation group and by sample size."""
    has = t[t["diff_one_year_pp"].notna()].copy()
    reval = has["revaluation_tax_year"].map(
        {2026: "On the 2026 revaluation list", 2027: "On the 2027 revaluation list"}).fillna("On neither list")
    size = pd.Series(np.where(has["our_n_classes_1_2_4"] >= config.MIN_SALES_SHOW,
                              f"{config.MIN_SALES_SHOW} or more sales", f"Under {config.MIN_SALES_SHOW} sales"),
                     index=has.index)
    rows = []
    for name, key in [("Revaluation", reval), ("Sample size", size)]:
        for value, g in has.groupby(key, sort=True):
            rows.append({"Group": f"{name}: {value}", "Towns": len(g),
                         "Within 1 point": int((g["diff_one_year_pp"].abs() <= 1).sum()),
                         "Median one-year gap": float(g["diff_one_year_pp"].median()),
                         "Median plain-average gap": float(g["diff_simple_mean_pp"].median())})
    return pd.DataFrame(rows)


def _yes(x):
    """Show a true/false/blank cell as yes, no, or a dash."""
    return "—" if pd.isna(x) else ("yes" if x else "no")


