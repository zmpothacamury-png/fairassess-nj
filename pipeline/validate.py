def write_report(t, s, path=config.VALIDATION_MD):
    """Put the generated block into docs/validation.md, keeping everything outside the markers."""
    block = generated_block(t, s)
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if BEGIN_MARK in text and END_MARK in text:
        before = text.split(BEGIN_MARK)[0]
        after = text.split(END_MARK, 1)[1]
        text = before + block + after
    else:
        text = text.rstrip() + ("\n\n" if text else "") + block + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


